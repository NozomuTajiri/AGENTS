/**
 * プロンプト A: 事実の構造化
 *
 * 文字起こしから「誰が・どんな課題（ペインポイント）を・どの文脈で発言したか」を
 * 事実のみ箇条書きで抽出する。憶測・解釈は禁止。
 */

export const PROMPT_A_SYSTEM = `あなたは熟練の議事録アナリストです。
発言者ごとの事実関係を、解釈や推測を一切交えずに構造化して抽出することに特化しています。
出力は日本語で行ってください。`;

export interface PromptAInput {
  customerName?: string;
  meetingPurpose?: string;
  transcript: string; // "山田: ...\n田尻: ..." の形式
}

export function renderPromptA(input: PromptAInput): string {
  const header = [
    `# 入力情報`,
    `- 顧客名: ${input.customerName ?? '不明'}`,
    `- ミーティング目的: ${input.meetingPurpose ?? '不明'}`,
    ``,
    `# 文字起こし（話者ラベル付き）`,
    '```',
    input.transcript,
    '```',
  ].join('\n');

  const instruction = `
# タスク
上記の文字起こしを読み込み、以下の **観点ごとに** 事実のみを箇条書きで抽出してください。
推測・解釈・主観評価は **絶対に含めない** こと。

## 出力フォーマット（Markdown）
### 1. 発言者一覧
- 話者名: 役割（推測ではなく自己紹介や肩書きの発言から特定できた場合のみ）

### 2. ペインポイント（顧客が言葉で表明した課題）
- [話者] 発言の要約（30文字以内）— 引用元の発話の一部抜粋

### 3. 数値・事実情報
- KPI / 売上 / 件数 / 期日など、数値で表現された事実を列挙

### 4. 決定事項
- 会議内で「やる/やらない」「期日」「担当」が確定したもののみ

### 5. 未解決の論点
- 会議内で結論が出なかった事項を列挙

# 制約
- 解釈や仮説は次工程（プロンプトB）で扱うため、ここでは **事実のみ**。
- 文字起こしに存在しない情報を補完しない（ハルシネーション禁止）。
`;

  return `${header}\n${instruction}`;
}
