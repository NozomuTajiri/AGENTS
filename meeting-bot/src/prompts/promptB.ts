/**
 * プロンプト B: 付加価値の分析（価値主義経営）
 *
 * プロンプト A の構造化された事実を入力に、
 * 「顧客がまだ気づいていない潜在ニーズ」「提供できる付加価値」を仮説立てる。
 */

export const PROMPT_B_SYSTEM = `あなたは「価値主義経営」を提唱するシニアコンサルタントです。
顧客の表層的な課題から、まだ言語化されていない潜在ニーズを引き出し、
高付加価値な提案に転換することを得意としています。
出力は日本語で行ってください。`;

export interface PromptBInput {
  customerName?: string;
  meetingPurpose?: string;
  promptAOutput: string;
}

export function renderPromptB(input: PromptBInput): string {
  return [
    `# 入力情報`,
    `- 顧客名: ${input.customerName ?? '不明'}`,
    `- ミーティング目的: ${input.meetingPurpose ?? '不明'}`,
    ``,
    `# プロンプトAの出力（事実）`,
    input.promptAOutput,
    ``,
    `# タスク`,
    `上記の事実をもとに、以下を出力してください。`,
    ``,
    `## 1. 潜在ニーズ仮説（3つ）`,
    `各仮説について、`,
    `- 仮説（1文）`,
    `- 根拠となった発言や事実（プロンプトA からの引用）`,
    `- 仮説の確からしさ: 高/中/低`,
    ``,
    `## 2. 提供可能な付加価値（3つ）`,
    `各付加価値について、`,
    `- 価値の名前（短く）`,
    `- 提供方法（プロダクト・サービス・伴走支援など）`,
    `- 想定される顧客便益（数値で語れるならKPIを推定）`,
    ``,
    `## 3. リスク・前提条件`,
    `- 上記仮説が崩れる条件を 2〜3 個挙げる`,
    ``,
    `# 制約`,
    `- 事実とは明確に分けて「仮説」「推定」と明記すること。`,
    `- 顧客の実際の発言と乖離した飛躍は避ける。`,
  ].join('\n');
}
